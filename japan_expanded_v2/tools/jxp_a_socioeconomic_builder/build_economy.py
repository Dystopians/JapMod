def validate_model() -> None:
    if len(CRISES) != 4 or len({crisis.key for crisis in CRISES}) != 4:
        raise ValueError("economy plan must define exactly four unique estate crises")
    crisis_keys = {crisis.key for crisis in CRISES}
    if set(CRISIS_START_YEARS) != crisis_keys:
        raise ValueError("every estate crisis needs one historical chronology gate")
    if set(CRISIS_RECOVERY_CHECKS) != crisis_keys or any(
        len(checks) < 3 for checks in CRISIS_RECOVERY_CHECKS.values()
    ):
        raise ValueError("every estate crisis needs a multi-factor organic recovery")
    if set(CRISIS_DEBUG_TOKENS) != crisis_keys or len(
        set(CRISIS_DEBUG_TOKENS.values())
    ) != 4:
        raise ValueError("every estate crisis needs one unique debug token")
    if len(COMPANIES) != 5 or len({company.key for company in COMPANIES}) != 5:
        raise ValueError("economy plan must define exactly five unique domestic companies")
    if len(MARKET_EVENT_TOPICS) != 30 or len(COMPANY_EVENT_TOPICS) != 20:
        raise ValueError("economy library must contain 30 market and 20 company events")
    if len(B_REQUESTS) != 5:
        raise ValueError("economy plan must expose exactly five B request flags")
    if len(MARKET_STAGE_SUPPORT) != 4:
        raise ValueError("each market stage must define two-of-three era support")
    if any(len(requirements) != 3 for requirements in MARKET_STAGE_SUPPORT):
        raise ValueError("market era support requires exactly three attributes")
    company_keys = {company.key for company in COMPANIES}
    if set(COMPANY_FORMATION_CHECKS) != company_keys:
        raise ValueError("every company must own one historical formation gate")
    if set(COMPANY_AI_PROFILES) != company_keys:
        raise ValueError("every company must own one differentiated AI profile")
    if set(COMPANY_FOUNDER_AFFINITIES) != company_keys:
        raise ValueError("every company must consume founder legacy affinities")
    founder_classes = {
        "commercial",
        "maritime",
        "bureaucratic",
        "communal",
        "frontier",
    }
    if any(
        len(affinities) != 2 or not set(affinities) <= founder_classes
        for affinities in COMPANY_FOUNDER_AFFINITIES.values()
    ):
        raise ValueError("each company must own two valid founder affinities")
    if {
        affinity
        for affinities in COMPANY_FOUNDER_AFFINITIES.values()
        for affinity in affinities
    } != founder_classes:
        raise ValueError("company formation must consume all five founder classes")
    if UNIFICATION_METHODS != ("blade", "edict", "league"):
        raise ValueError("unification method migration contract drift")
    if LEGACY_FOUNDATION_MODIFIERS != (
        "jxp_24_foundation_blade",
        "jxp_24_foundation_edict",
        "jxp_24_foundation_league",
    ):
        raise ValueError("legacy foundation migration inputs drift")
    director_keys = {director for director, _title, _desc in DIRECTORS}
    if set(DIRECTOR_MODIFIERS) != director_keys:
        raise ValueError("every director model must own one practical modifier")
    if MARKET_EVENT_MIN_YEARS != {19: 1730}:
        raise ValueError("Dojima clearing crisis must remain gated to 1730")
    expected_requests = {
        "red_seal_overseas",
        "pacific_charter",
        "southern_seas",
        "northern_seas",
        "continental",
    }
    if {key for key, _title, _desc in B_REQUESTS} != expected_requests:
        raise ValueError("B request interface drift")
    expected_bridges = {
        key: (
            f"jxp_b_112_agent_a_{key}_request_visible_trigger",
            f"jxp_b_112_agent_a_{key}_request_ready_trigger",
        )
        for key in expected_requests
    }
    if B_REQUEST_BRIDGES != expected_bridges:
        raise ValueError("B request bridge trigger drift")


