def _find_top_level_block_span(data: bytes, key: str) -> tuple[int, int] | None:
    match = re.search(
        rb"(?m)^(?:\xef\xbb\xbf)?"
        + re.escape(key.encode("ascii"))
        + rb"[ \t]*=[ \t]*\{",
        data,
    )
    if match is None:
        return None
    brace = data.find(b"{", match.start())
    depth = 0
    quoted = False
    escaped = False
    comment = False
    for index in range(brace, len(data)):
        byte = data[index]
        if comment:
            if byte in (10, 13):
                comment = False
            continue
        if quoted:
            if escaped:
                escaped = False
            elif byte == 92:
                escaped = True
            elif byte == 34:
                quoted = False
            continue
        if byte == 35:
            comment = True
        elif byte == 34:
            quoted = True
        elif byte == 123:
            depth += 1
        elif byte == 125:
            depth -= 1
            if depth == 0:
                end = index + 1
                if data[end : end + 2] == b"\r\n":
                    end += 2
                elif data[end : end + 1] == b"\n":
                    end += 1
                return match.start(), end
    raise ValueError(f"unterminated top-level block {key}")


def _top_level_block_bytes(data: bytes, key: str) -> bytes:
    span = _find_top_level_block_span(data, key)
    if span is None:
        raise ValueError(f"missing frozen slot-4/5 series {key}")
    return data[span[0] : span[1]]


def _strip_legacy_series(data: bytes, *, normalize_eof: bool = False) -> bytes:
    result = data
    removed = False
    for series, _slot in TOMBSTONE_SERIES:
        while True:
            span = _find_top_level_block_span(result, series)
            if span is None:
                break
            result = result[: span[0]] + result[span[1] :]
            removed = True
    # Removing a terminal A block can leave a whitespace-only final row.  A
    # previous generation may already have removed that block, so normalize
    # exterior EOF whitespace on every pass. Frozen slot-4/5 block bytes stay
    # guarded separately by the manifest hashes.
    if removed or normalize_eof:
        newline = b"\r\n" if b"\r\n" in result else b"\n"
        result = result.rstrip(b" \t\r\n")
        if result:
            result += newline
    return result


def _load_frozen_manifest() -> dict[str, object]:
    path = MOD_ROOT / FROZEN_MANIFEST_PATH
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict) or value.get("schema_version") != 2:
        raise ValueError("frozen_mission_surface.json must use schema_version 2")
    return value


def _validate_frozen_surface(
    manifest: dict[str, object],
    overrides: dict[Path, bytes] | None = None,
) -> None:
    overrides = overrides or {}
    whole = manifest.get("whole_file_sha256")
    blocks = manifest.get("slot_series_sha256")
    if not isinstance(whole, dict) or not isinstance(blocks, dict):
        raise ValueError("frozen mission manifest tables are malformed")
    for relative, expected in whole.items():
        path = Path(str(relative))
        payload = overrides.get(path, (MOD_ROOT / path).read_bytes())
        actual = hashlib.sha256(payload).hexdigest()
        if actual != expected:
            raise ValueError(f"frozen B mission file drift: {path}: {actual} != {expected}")
    for relative, records in blocks.items():
        path = Path(str(relative))
        if not isinstance(records, dict):
            raise ValueError(f"frozen block record is malformed: {path}")
        payload = overrides.get(path, (MOD_ROOT / path).read_bytes())
        for series, expected in records.items():
            block = _top_level_block_bytes(payload, str(series))
            actual = hashlib.sha256(block).hexdigest()
            if actual != expected:
                raise ValueError(
                    f"frozen slot-4/5 block drift: {path}::{series}: {actual} != {expected}"
                )


def _load_escape_module():
    path = REPO_ROOT / "skills/eu4-modding/scripts/escape_eu4_special_localisation.py"
    spec = importlib.util.spec_from_file_location("jxp_escape_eu4_special", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load localisation encoder: {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _validate_authority() -> None:
    if len(CAPITAL_TASKS) != 35:
        raise ValueError("capital task contract must contain exactly 35 tasks")
    if len(CAPITAL_REWARD_DETAILS) != 35 or len(CAPITAL_STAKEHOLDERS) != 35:
        raise ValueError("every capital task needs a unique consequence and stakeholder pair")
    if len(ROUTE_PROFILES) != 12 or any(len(profile.titles) != 8 for profile in ROUTE_PROFILES):
        raise ValueError("domestic route contract must contain 12 profiles with eight tasks each")
    if len(COMMERCIAL_TITLES) != 21:
        raise ValueError("Commercial Council contract must contain exactly 21 tasks")
    if len(COMMERCIAL_REWARD_DETAILS) != 21 or len(COMMERCIAL_STAKEHOLDERS) != 21:
        raise ValueError("every Commercial Council task needs a consequence and stakeholder pair")
    if set(POLITICAL_CAPSTONE_BRIDGES) != {"uncommitted", "open", "imperial"}:
        raise ValueError("exactly three political capstones must bridge into route node eight")
    if len(LEGACY_SUPERSEDED_MISSION_MODIFIERS) != 22 or len(
        set(LEGACY_SUPERSEDED_MISSION_MODIFIERS)
    ) != 22:
        raise ValueError("legacy mission modifier migration must own exactly 22 unique inputs")
    if any("tradeoff" in modifier for modifier in LEGACY_SUPERSEDED_MISSION_MODIFIERS):
        raise ValueError("nonexistent A105 tradeoff modifiers may not enter migration")
    policy_ids = [event.event_id for event in CAPITAL_POLICY_EVENTS]
    if len(policy_ids) != 14 or len(set(policy_ids)) != 14:
        raise ValueError("capital policy surface must contain fourteen unique events")
    if len(policy_choice_flags()) != 46:
        raise ValueError("capital policy surface must publish 46 distinct outcome flags")
    ids = [task.mission_id for task in CAPITAL_TASKS]
    ids.extend(mission for profile in ROUTE_PROFILES for mission in route_ids(profile))
    ids.extend(commercial_id(index) for index in range(1, 22))
    if len(ids) != 152 or len(set(ids)) != 152:
        raise ValueError("mission layout must contain 152 globally unique mission ids")
    origins = [origin for values in FOUNDER_ORIGINS.values() for origin in values]
    if len(origins) != 37 or len(set(origins)) != 37:
        raise ValueError("founder economic legacy must classify exactly 37 main-mod origins")
    map_origins = [
        origin for values in MAP_FOUNDER_ORIGINS.values() for origin in values
    ]
    if set(MAP_FOUNDER_ORIGINS) != set(FOUNDER_ORIGINS):
        raise ValueError("main and companion founder categories must use the same five classes")
    if len(map_origins) != 30 or len(set(map_origins)) != 30:
        raise ValueError("founder economic legacy must classify exactly 30 companion-map origins")
    if len(origins) + len(map_origins) != 67:
        raise ValueError("founder economic legacy must classify all 67 daimyo")
    for profile in ROUTE_PROFILES:
        positions = [position for position, _ in profile.legacy_by_position]
        legacy = [mission for _, mission in profile.legacy_by_position]
        if len(positions) != len(set(positions)) or not set(positions) <= set(range(1, 9)):
            raise ValueError(f"invalid legacy positions for {profile.key}")
        if len(legacy) != len(set(legacy)):
            raise ValueError(f"duplicate legacy ids for {profile.key}")


def render_outputs() -> dict[Path, bytes]:
    _validate_authority()
    manifest = _load_frozen_manifest()
    _validate_frozen_surface(manifest)
    source_loc = render_localisation()
    escape = _load_escape_module()
    outputs: dict[Path, bytes] = {
        MISSION_PATH: render_missions().encode("utf-8"),
        TRIGGER_PATH: render_triggers().encode("utf-8"),
        EFFECT_PATH: render_effects().encode("utf-8"),
        MODIFIER_PATH: render_modifiers().encode("utf-8"),
        REFORM_PATH: render_reforms().encode("utf-8"),
        EVENT_PATH: render_events().encode("utf-8"),
        DISASTER_PATH: render_disaster().encode("utf-8"),
        DECISION_PATH: render_decisions().encode("utf-8"),
        DEBUG_EFFECT_PATH: render_debug_effects().encode("utf-8"),
        DEBUG_DECISION_PATH: render_debug_decisions().encode("utf-8"),
        SOURCE_LOC_PATH: source_loc.encode("utf-8"),
        ACTIVE_LOC_PATH: escape.escape_text(source_loc).encode("utf-8-sig"),
    }
    # Remove only the sixteen superseded A series.  All surrounding bytes,
    # including mixed-file slot-four/five blocks, remain byte-for-byte intact.
    mixed_paths = set(manifest["slot_series_sha256"])
    for path in sorted((MOD_ROOT / "missions").glob("*.txt")):
        relative = path.relative_to(MOD_ROOT)
        payload = path.read_bytes()
        stripped = _strip_legacy_series(
            payload,
            normalize_eof=relative.as_posix() in mixed_paths,
        )
        if stripped != payload:
            outputs[relative] = stripped
    _validate_frozen_surface(manifest, outputs)
    return outputs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated outputs drift")
    args = parser.parse_args(argv)
    try:
        outputs = render_outputs()
    except (OSError, ValueError, RuntimeError, json.JSONDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    drift: list[str] = []
    for relative, expected in outputs.items():
        path = MOD_ROOT / relative
        actual = path.read_bytes() if path.is_file() else None
        if actual == expected:
            continue
        if args.check:
            drift.append(relative.as_posix())
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(expected)
        print(f"wrote {relative.as_posix()}")
    if drift:
        print("generated outputs drift: " + ", ".join(sorted(drift)), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
