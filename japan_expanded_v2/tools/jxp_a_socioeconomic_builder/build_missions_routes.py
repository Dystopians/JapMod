def _mission_block(
    mission_id: str,
    *,
    position: int,
    icon: str,
    required: str | None,
    triggers: Iterable[str],
    reward_lines: Iterable[str],
    replay_safe_lines: Iterable[str] = (),
) -> list[str]:
    lines = [f"\t{mission_id} = {{", f"\t\ticon = {icon}", f"\t\tposition = {position}"]
    if required:
        lines.append(f"\t\trequired_missions = {{ {required} }}")
    else:
        lines.append("\t\trequired_missions = { }")
    lines.extend(("\t\ttrigger = {", *[f"\t\t\t{line}" for line in triggers], "\t\t}"))
    lines.append("\t\teffect = {")
    replay_safe = tuple(replay_safe_lines)
    if replay_safe:
        lines.append("\t\t\thidden_effect = {")
        lines.extend(f"\t\t\t\t{line}" for line in replay_safe)
        lines.append("\t\t\t}")
    lines.extend(
        (
            "\t\t\tif = {",
            "\t\t\t\tlimit = { NOT = { has_country_flag = jxp_a_105_mission_replay_in_progress } }",
            f"\t\t\t\tcustom_tooltip = {mission_id}_reward_tt",
        )
    )
    for stage, trigger in (
        (4, "jxp_a_market_stage_at_least_4_trigger = yes"),
        (3, "jxp_a_market_stage_at_least_3_trigger = yes"),
        (2, "jxp_a_market_stage_at_least_2_trigger = yes"),
        (1, "jxp_a_has_any_market_stage_trigger = yes"),
    ):
        keyword = "if" if stage == 4 else "else_if"
        lines.extend(
            (
                f"\t\t\t\t{keyword} = {{",
                f"\t\t\t\t\tlimit = {{ {trigger} }}",
                f"\t\t\t\t\tcustom_tooltip = jxp_a_105_progress_market_{stage}_tt",
                "\t\t\t\t}",
            )
        )
    lines.extend(
        (
            "\t\t\t\telse = { custom_tooltip = jxp_a_105_progress_market_0_tt }",
        )
    )
    for companies in range(5, 0, -1):
        keyword = "if" if companies == 5 else "else_if"
        lines.extend(
            (
                f"\t\t\t\t{keyword} = {{",
                f"\t\t\t\t\tlimit = {{ jxp_a_company_has_at_least_{companies}_trigger = yes }}",
                f"\t\t\t\t\tcustom_tooltip = jxp_a_105_progress_companies_{companies}_tt",
                "\t\t\t\t}",
            )
        )
    lines.extend(
        (
            "\t\t\t\telse = { custom_tooltip = jxp_a_105_progress_companies_0_tt }",
            "\t\t\t\thidden_effect = {",
        )
    )
    lines.extend(f"\t\t\t\t\t{line}" for line in reward_lines)
    lines.extend(("\t\t\t\t}", "\t\t\t}", "\t\t}", "\t}", ""))
    return lines


