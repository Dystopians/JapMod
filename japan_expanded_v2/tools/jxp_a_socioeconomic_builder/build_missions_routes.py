@dataclass(frozen=True, slots=True)
class CapitalTask:
    slug: str
    title: str
    desc: str
    legacy_id: str | None = None

    @property
    def mission_id(self) -> str:
        return self.legacy_id or f"jxp_a_105_cap_{self.slug}"


@dataclass(frozen=True, slots=True)
class RouteProfile:
    key: str
    name: str
    context: str
    crisis: str
    titles: tuple[str, ...]
    legacy_by_position: tuple[tuple[int, str], ...]
    model_modifiers: tuple[tuple[str, str], ...]

    def mission_id(self, position: int) -> str:
        legacy = dict(self.legacy_by_position).get(position)
        return legacy or f"jxp_a_105_{self.key}_domestic_{position}"


@dataclass(frozen=True, slots=True)
class PoliticalCapstoneBridge:
    legacy_mission_id: str
    active_trigger: str
    requirements: tuple[str, ...]
    modifier_id: str
    power_reward: str
    charter_name: str


@dataclass(frozen=True, slots=True)
class PolicyOption:
    key: str
    title: str
    flag: str | None
    effects: tuple[str, ...]
    trigger: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class PolicyEvent:
    event_id: int
    title: str
    desc: str
    options: tuple[PolicyOption, ...]


